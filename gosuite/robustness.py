"""Robustness of planned paths to a misspecified grasp-error model (no replanning).

    python -m gosuite.robustness --config configs/robustness_crisp_v0.4.json

Every method planned with the protocol model (2 mm / 1 deg per axis, combined).  Here its stored test paths
are executed again under other error models: the standard deviations scaled by s (common random numbers:
the same underlying normal draws, scaled), and translation-only / rotation-only errors at s = 1.  A method
that merely fits its planning model loses its advantage when the model is wrong; a method that exploits the
geometry correctly should keep its ranking.  Writes robustness.json, robustness.md and robustness.png.
"""
import argparse
import hashlib
import json
from multiprocessing import Pool
from pathlib import Path
import numpy as np
from .evaluate import evaluate_path
from .report import bootstrap


def jobs(cfg):
    suite = Path(cfg['suite'])
    manifest = {e['id']: e for e in json.loads((suite / 'manifest.json').read_text())['tasks']}
    out = []
    for m in cfg['methods']:
        if m.get('witness'):
            paths = {i: (suite / e[m['witness']], e[m['witness'].replace('_file', '_sha256')]) for i, e in manifest.items()
                     if e['split'] == cfg['split']}
        else:
            paths = {}
            for f in sorted(Path(m['results']).glob('runs/*/*.json')):
                r = json.loads(f.read_text())
                if r['label'] == m['label'] and r['split'] == cfg['split'] and r['seed'] == m.get('seed', 0) and r['nominal_valid']:
                    paths[r['task_id']] = (Path(m['results']) / r['trajectory'], r['trajectory_sha256'])
        for task, (path, sha) in sorted(paths.items()):
            for cond in cfg['conditions']:
                out.append(dict(method=m['name'], task=task, level=manifest[task]['level'], family=manifest[task]['family'],
                                scene=str(suite / manifest[task]['file']), path=str(path), sha=sha, **cond))
    return out


def run(job):
    path = Path(job['path'])
    if hashlib.sha256(path.read_bytes()).hexdigest() != job['sha']:
        raise RuntimeError(f'trajectory changed: {path}')
    scene = json.loads(Path(job['scene']).read_text())
    ev = evaluate_path(scene, np.load(path), 256, job['scale'], job['mode'], keep_outcomes=False, metrics=False)
    return dict({k: v for k, v in job.items() if k not in ('scene', 'path', 'sha')}, success=ev.get('success_rate', 0.))


def label(cond):
    return f"{cond['mode'].replace('_only', '-only')}, s = {cond['scale']:g}"


def summarise(cfg, rows):
    """Mean over ALL tasks of the split; a task without a valid stored path counts as 0 (as in the main table)."""
    names = [m['name'] for m in cfg['methods']]
    tasks = [e['id'] for e in json.loads((Path(cfg['suite']) / 'manifest.json').read_text())['tasks'] if e['split'] == cfg['split']]
    table = {}
    for n in names:
        for c in cfg['conditions']:
            per_task = dict.fromkeys(tasks, 0.)
            per_task.update({r['task']: r['success'] for r in rows if r['method'] == n and r['scale'] == c['scale'] and r['mode'] == c['mode']})
            table.setdefault(n, {})[label(c)] = dict(mean=float(np.mean(list(per_task.values()))), ci95=bootstrap(per_task), tasks=len(per_task))
    return table


def markdown(cfg, table):
    conds = [label(c) for c in cfg['conditions']]
    out = [f"# {cfg['name']}", '', cfg['description'], '',
           'Task success (%) of the stored paths re-executed under each grasp-error model (mean over test tasks, '
           '95% bootstrap CI over tasks). s scales every standard deviation; planning always used s = 1, combined.', '',
           'Generated by `python -m gosuite.robustness`; do not edit by hand.', '',
           '| Method | ' + ' | '.join(conds) + ' |', '|---|' + '---:|' * len(conds)]
    for n, row in table.items():
        out.append(f'| {n} | ' + ' | '.join(f"{100 * row[c]['mean']:.1f} [{100 * row[c]['ci95'][0]:.1f}, {100 * row[c]['ci95'][1]:.1f}]"
                                             for c in conds) + ' |')
    return '\n'.join(out) + '\n'


def figure(cfg, table, path):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    from .crisp_figures import ACCENT, METHOD, ORACLE, _style
    from .figures import INK, INK2, SURFACE, GRID
    combined = [c for c in cfg['conditions'] if c['mode'] == 'combined']
    single = [c for c in cfg['conditions'] if c['mode'] != 'combined']
    fig, (ax, bx) = plt.subplots(1, 2, figsize=(10, 3.9), dpi=170, gridspec_kw=dict(width_ratios=[1.5, 1]))
    fig.patch.set_facecolor(SURFACE)
    names = list(table)
    style = {}
    for n in names:
        colour = ORACLE if 'oracle' in n.lower() else (ACCENT if 'CRISP' in n else METHOD)
        style[n] = (colour, '--' if ('straight' in n.lower() or 'B6' in n) else '-')
    _style(ax)
    ax.yaxis.grid(True, color=GRID, linewidth=.8, zorder=0)
    for n in names:
        xs = [c['scale'] for c in combined]
        ys = [100 * table[n][label(c)]['mean'] for c in combined]
        ax.plot(xs, ys, style[n][1], color=style[n][0], linewidth=2, marker='o', markersize=4.5, label=n, zorder=3)
    ax.axvline(1, color=INK2, linewidth=.8, linestyle=':', zorder=1)
    ax.text(1.02, 3, 'planning model', fontsize=7, color=INK2)
    ax.set_ylim(0, 100)
    ax.set_xticks([c['scale'] for c in combined])
    ax.set_xlabel('grasp-error scale at execution (s x 2 mm / 1 deg)', fontsize=8, color=INK2)
    ax.set_ylabel('task success (%)', fontsize=8, color=INK2)
    ax.set_title('Scaled error (planned for s = 1)', fontsize=8.5, color=INK)
    ax.legend(frameon=False, fontsize=7, labelcolor=INK, loc='lower left')
    _style(bx)
    bx.xaxis.grid(False)
    bx.yaxis.grid(True, color=GRID, linewidth=.8, zorder=0)
    width = .8 / len(names)
    for j, n in enumerate(names):
        xs = [i + (j - (len(names) - 1) / 2) * width for i in range(len(single))]
        ys = [100 * table[n][label(c)]['mean'] for c in single]
        bx.bar(xs, ys, width=width * .92, color=style[n][0], alpha=.55 if style[n][1] == '--' else 1., zorder=2)
    bx.set_xticks(range(len(single)))
    bx.set_xticklabels([c['mode'].replace('_only', '-only') + ' error' for c in single], fontsize=8, color=INK)
    bx.set_ylim(50, 100)
    bx.set_ylabel('task success (%)', fontsize=8, color=INK2)
    bx.set_title('One error component only (s = 1); bars in legend order', fontsize=8.5, color=INK)
    fig.tight_layout()
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser(description='Re-execute stored paths under misspecified grasp-error models.')
    ap.add_argument('--config', required=True)
    ap.add_argument('--workers', type=int)
    ap.add_argument('--figure-only', action='store_true', help='redraw the figure from robustness.json')
    a = ap.parse_args()
    cfg = json.loads(Path(a.config).read_text())
    out = Path(cfg['output'])
    out.mkdir(parents=True, exist_ok=True)
    if a.figure_only:
        figure(cfg, json.loads((out / 'robustness.json').read_text())['table'], out / 'robustness.png')
        return
    todo = jobs(cfg)
    print(f'{len(todo)} re-executions', flush=True)
    with Pool(a.workers or cfg.get('workers', 20), maxtasksperchild=20) as pool:
        rows = pool.map(run, todo, chunksize=4)
    table = summarise(cfg, rows)
    (out / 'robustness.json').write_text(json.dumps(dict(config=cfg, table=table, runs=rows), indent=1) + '\n')
    (out / 'robustness.md').write_text(markdown(cfg, table))
    figure(cfg, table, out / 'robustness.png')
    print(markdown(cfg, table))


if __name__ == '__main__':
    main()
