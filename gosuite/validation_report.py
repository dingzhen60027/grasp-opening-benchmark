"""Render the validity analyses (gosuite.validate) as Markdown tables and two figures.

    python -m gosuite.validation_report results/suite_v0.3/validation
"""
import argparse
import json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402

SURFACE, INK, INK2, GRID = '#fcfcfb', '#0b0b0b', '#52514e', '#e4e3df'
SUCCESS, PATH_FAIL, GOAL_FAIL = '#2a78d6', '#eb6834', '#8f8e88'   # categorical slots 1-2 + a neutral for "unavoidable"
FAMILY_COLORS = {'rack': '#2a78d6', 'rebar': '#eb6834', 'lathe': '#1baf7a', 'tote': '#eda100'}
FAMILY_NAMES = {'rack': 'F1 Rack', 'rebar': 'F2 Rebar', 'lathe': 'F3 Lathe', 'tote': 'F4 Tote'}
LEVELS = ['easy', 'medium', 'hard']


def _style(ax):
    ax.set_facecolor(SURFACE)
    ax.yaxis.grid(True, color=GRID, linewidth=.8, zorder=0)
    ax.set_axisbelow(True)
    for side in ('top', 'right', 'left'):
        ax.spines[side].set_visible(False)
    ax.spines['bottom'].set_color(GRID)
    ax.tick_params(length=0, labelsize=8.5, colors=INK2)


def headroom_figure(v, out):
    cells = [(f, l) for f in FAMILY_NAMES for l in LEVELS]
    h = [v['headroom'][f'{f}/{l}'] for f, l in cells]
    fig, ax = plt.subplots(figsize=(9.6, 4.3), dpi=170)
    fig.patch.set_facecolor(SURFACE)
    _style(ax)
    xs = [i + i // 3 * .6 for i in range(len(cells))]
    succ = [100 * c['reference_success'] for c in h]
    path = [100 * c['path_failure'] for c in h]
    goal = [100 * c['goal_failure'] for c in h]
    ax.bar(xs, succ, width=.82, color=SUCCESS, edgecolor=SURFACE, linewidth=1.2, label='reference success', zorder=2)
    ax.bar(xs, path, bottom=succ, width=.82, color=PATH_FAIL, edgecolor=SURFACE, linewidth=1.2,
           label='failure along the path (a better path could avoid it)', zorder=2)
    ax.bar(xs, goal, bottom=[a + b for a, b in zip(succ, path)], width=.82, color=GOAL_FAIL, edgecolor=SURFACE, linewidth=1.2,
           label='failure at the goal state (no path ending there avoids it)', zorder=2)
    for x, c in zip(xs, h):
        ax.plot([x - .41, x + .41], [100 * c['region_bound']] * 2, color=INK, linewidth=1.4, zorder=3)
    ax.plot([], [], color=INK, linewidth=1.4, label='best goal pose inside the tolerance region (upper bound)')
    ax.set_xticks(xs)
    ax.set_xticklabels([l for _, l in cells], fontsize=8, color=INK2)
    for k, fam in enumerate(FAMILY_NAMES):
        ax.text(xs[3 * k + 1], -17, FAMILY_NAMES[fam], ha='center', va='top', fontsize=9.5, color=INK)
    ax.set_ylim(0, 103)
    ax.set_yticks(range(0, 101, 20))
    ax.set_yticklabels([f'{t}%' for t in range(0, 101, 20)])
    ax.legend(loc='upper left', bbox_to_anchor=(0, 1.3), ncol=2, frameon=False, fontsize=8, labelcolor=INK, handlelength=1.2)
    fig.suptitle('Where the reference paths fail: path vs goal state', x=.07, ha='left', y=.99, fontsize=11.5, color=INK, fontweight='bold')
    fig.subplots_adjust(left=.07, right=.99, top=.74, bottom=.17)
    fig.savefig(out / 'headroom.png', facecolor=SURFACE)
    plt.close(fig)


def sensitivity_figure(v, out):
    fig, ax = plt.subplots(figsize=(7.2, 4.1), dpi=170)
    fig.patch.set_facecolor(SURFACE)
    _style(ax)
    for fam, color in FAMILY_COLORS.items():
        sweep = v['sensitivity'][f'{fam}/all']['combined']
        xs = [float(s) for s in sweep]
        ys = [100 * sweep[s] for s in sweep]
        ax.plot(xs, ys, color=color, linewidth=2, marker='o', markersize=4.5, markeredgecolor=SURFACE, markeredgewidth=1.2, zorder=3)
        ax.text(xs[-1] + .06, ys[-1], FAMILY_NAMES[fam], va='center', fontsize=8.5, color=INK)
    ax.axvline(1, color=GRID, linewidth=1.2, zorder=1)
    ax.text(1.03, 101, 'protocol default\n(2 mm, 1 deg)', fontsize=7.5, color=INK2, va='top')
    ax.set_xlim(-.05, 3.45)
    ax.set_ylim(0, 103)
    ax.set_yticks(range(0, 101, 20))
    ax.set_yticklabels([f'{t}%' for t in range(0, 101, 20)])
    ax.set_xlabel('grasp-error scale (x protocol sigma)', fontsize=8.5, color=INK2)
    ax.set_ylabel('reference success', fontsize=8.5, color=INK2)
    fig.suptitle('Sensitivity to grasp-error magnitude (dev split, all levels)', x=.09, ha='left', y=.98, fontsize=11, color=INK, fontweight='bold')
    fig.subplots_adjust(left=.09, right=.97, top=.88, bottom=.13)
    fig.savefig(out / 'sensitivity.png', facecolor=SURFACE)
    plt.close(fig)


def markdown(v):
    pct = lambda x: f'{100 * x:.1f}%'
    lines = ['# Validation of gosuite v0.3', '', 'Generated by `python -m gosuite.validate` and `python -m gosuite.validation_report`. '
             f'Every number uses the protocol draws ({v["episodes"]} episodes per task, 2 mm / 1 deg).', '',
             '## 1. Headroom: where do the reference paths fail?', '',
             'A failure at the goal state happens for the drawn grasp error even with the payload parked at the goal '
             'configuration. Every path that ends there loses that episode. "Path failure" is the rest: episodes that a '
             'better path ending at the same goal could win. "Goal-region bound" is the best static success over goal '
             'poses inside the tolerance region.', '',
             '| Family | Level | Reference success | Path failure | Goal-state failure | Bound at q_goal_reference | Goal-region bound |',
             '|---|---|---:|---:|---:|---:|---:|']
    for f in list(FAMILY_NAMES) + ['all']:
        for l in LEVELS + ['all']:
            h = v['headroom'][f'{f}/{l}']
            lines.append(f"| {f} | {l} | {pct(h['reference_success'])} | {pct(h['path_failure'])} | {pct(h['goal_failure'])} | "
                         f"{pct(h['bound'])} | {pct(h['region_bound'])} |")
    if v['headroom']['all/all'].get('straight_success') is not None:
        lines += ['', '### Risk-aware vs straight witness (v0.4)', '',
                  'Both witnesses end at the same goal pose. The straight one inserts along the goal line; the risk-aware one was '
                  'optimised on planning-stream draws only, so its success on the evaluation draws is an unbiased estimate.', '',
                  '| Family | Level | Straight witness | Risk-aware witness | Headroom (points) |', '|---|---|---:|---:|---:|']
        for f in list(FAMILY_NAMES) + ['all']:
            for l in LEVELS + ['all']:
                h = v['headroom'][f'{f}/{l}']
                lines.append(f"| {f} | {l} | {pct(h['straight_success'])} | {pct(h['reference_success'])} | "
                             f"{100 * (h['reference_success'] - h['straight_success']):+.1f} |")
    lines += ['', '![headroom](headroom.png)', '', '## 2. Evaluation-step convergence', '',
              '| Task | Success at 0.0025 rad | Success at 0.00125 rad | Episodes with a different outcome |', '|---|---:|---:|---:|']
    for c in v['step_convergence']:
        lines.append(f"| {c['id']} | {pct(c['success_step_0025'])} | {pct(c['success_step_00125'])} | {c['differing_episodes']} |")
    lines += ['', '## 3. Sensitivity to the grasp-error model (dev split)', '',
              f"Per-task success is monotone non-increasing in the error scale for every dev task: **{v['sensitivity_monotone']}**.", '',
              '| Family | x0 | x0.5 | x1 | x1.5 | x2 | x3 | translation only (x1) | rotation only (x1) |', '|---|---:|---:|---:|---:|---:|---:|---:|---:|']
    for f in list(FAMILY_NAMES) + ['all']:
        s = v['sensitivity'][f'{f}/all']
        lines.append(f"| {f} | " + ' | '.join(pct(s['combined'][k]) for k in s['combined']) +
                     f" | {pct(s['translation_only'])} | {pct(s['rotation_only'])} |")
    lines += ['', '![sensitivity](sensitivity.png)', '', '## 4. Difficulty descriptors', '',
              'Spearman rank correlation with reference success over all 96 tasks.', '',
              '| Descriptor | rho | p |', '|---|---:|---:|']
    for k, d in v['descriptor_correlation'].items():
        lines.append(f"| {k} | {d['spearman_rho']:.2f} | {d['p_value']:.1e} |")
    lines += ['', 'Tip sensitivity `c / (lever * sigma_r)` within each family: ' +
              ', '.join(f"{f} rho = {d['spearman_rho']:.2f}" for f, d in v['tip_sensitivity_within_family'].items()) + '.', '',
              '## 5. Variance components (reference success)', '', '| Cell | Between-task SD | Within-task binomial SE (256 episodes) |',
              '|---|---:|---:|']
    for k, d in v['variance'].items():
        lines.append(f"| {k} | {100 * d['between_task_sd']:.1f} pts | {100 * d['within_task_binomial_se_256']:.1f} pts |")
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser(description='Render validation results.')
    ap.add_argument('output', nargs='?', default='results/suite_v0.3/validation')
    out = Path(ap.parse_args().output)
    v = json.loads((out / 'validation.json').read_text())
    headroom_figure(v, out)
    sensitivity_figure(v, out)
    (out / 'validation.md').write_text(markdown(v))
    print('wrote', out / 'validation.md')


if __name__ == '__main__':
    main()
